/* Combien fait-il ?
 *
 * Pour convertir des degrés Celsius en degrés Fahrenheit, la formule est la suivante :
 * °F = (°C * 9/5) + 32
 * 
 * Voici une variable qui contient une température en degrés Celsius :
 *  - créer une variable tempFahrenheit
 *  - cette variable doit contenir la température convertie en degrés Fahrenheit de la variable tempCelsius
 *  - contrôler la valeur (résultat attendu : 77°F)
 */

const tempCelsius = 25;
const tempFahrenheit = (tempCelsius * 9/5) + 32;
console.log(tempFahrenheit);

